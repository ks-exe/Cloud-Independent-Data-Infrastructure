#!/usr/bin/env bash
# =============================================================================
# load-images.sh — Load container images from tar archives into Docker
# =============================================================================
# Usage: ./load-images.sh [images_directory]
#
# Loads all .tar image archives from the specified directory into the local
# Docker daemon. Used in air-gapped environments where images cannot be pulled
# from public registries.
#
# Requirements:
#   - Docker Engine >= 24.0
#   - Sufficient disk space for extracted images
#   - .tar files generated by save-images.sh
# =============================================================================

set -euo pipefail

# Default input directory
INPUT_DIR="${1:-./images}"

# Color output helpers
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

log_info() {
    echo -e "${GREEN}[INFO]${NC} $1"
}

log_warn() {
    echo -e "${YELLOW}[WARN]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

# Check prerequisites
check_prerequisites() {
    if ! command -v docker &> /dev/null; then
        log_error "Docker is not installed or not in PATH"
        exit 1
    fi

    if ! docker info &> /dev/null; then
        log_error "Docker daemon is not running or current user lacks permissions"
        exit 1
    fi
}

# Main execution
main() {
    check_prerequisites

    if [ ! -d "$INPUT_DIR" ]; then
        log_error "Directory not found: ${INPUT_DIR}"
        log_error "Usage: $0 [images_directory]"
        exit 1
    fi

    # Find all .tar files
    local tar_files
    tar_files=$(find "$INPUT_DIR" -maxdepth 1 -name "*.tar" -type f | sort)

    if [ -z "$tar_files" ]; then
        log_error "No .tar files found in ${INPUT_DIR}"
        exit 1
    fi

    local total
    total=$(echo "$tar_files" | wc -l)
    local count=0
    local failed=0
    local loaded=0

    log_info "Loading ${total} container image(s) from: ${INPUT_DIR}"
    log_info "========================================="

    while IFS= read -r tar_file; do
        count=$((count + 1))
        local filename
        filename=$(basename "$tar_file")
        local size
        size=$(du -h "$tar_file" | cut -f1)

        echo ""
        log_info "[${count}/${total}] Loading: ${filename} (${size})"

        # Verify tar integrity before loading
        if ! tar -tf "$tar_file" > /dev/null 2>&1; then
            log_error "  Archive is corrupted: ${filename}"
            failed=$((failed + 1))
            continue
        fi

        # Load the image
        if docker load -i "$tar_file" 2>&1 | while IFS= read -r line; do
            log_info "  ${line}"
        done; then
            loaded=$((loaded + 1))
        else
            log_error "  Failed to load: ${filename}"
            failed=$((failed + 1))
        fi
    done <<< "$tar_files"

    # Summary
    echo ""
    log_info "========================================="
    log_info "Image loading complete!"
    log_info "  Total archives: ${total}"
    log_info "  Successfully loaded: ${loaded}"
    log_info "  Failed: ${failed}"
    log_info "========================================="

    if [ "$failed" -gt 0 ]; then
        log_warn "Some images failed to load. Check the output above for details."
        exit 1
    fi

    # List loaded images
    echo ""
    log_info "Currently available images:"
    docker images --format "  {{.Repository}}:{{.Tag}} ({{.Size}})" | grep -E "postgres|clickhouse|redis|rabbitmq|elasticsearch|dagster|prometheus|grafana|cdp-" || true

    echo ""
    log_info "All images loaded successfully. Proceed with service startup."
}

main "$@"
